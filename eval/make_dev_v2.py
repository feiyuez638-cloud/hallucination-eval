def longctx(rng, k):
    """虚构小镇三段式长题：kind 0 设定内可答，1 对话中途更新过（以更新后为准），2 设定里没有（应答未知）。"""
    sur = "沈顾陆林许叶温程苏江韩秦白宋梁唐"
    giv = ["若溪", "砚秋", "知远", "听澜", "望舒", "景行", "疏桐", "照野", "怀瑾", "清和", "南乔", "既白", "云岫", "鹿鸣", "书禾"]
    jobs = ["钟表匠", "邮差", "面包师", "灯塔看守", "渡船船长", "药铺掌柜", "裁缝", "茶馆老板", "铁匠", "教书先生", "花匠", "木匠"]
    pets = ["灰猫", "黄狗", "鹦鹉", "白兔", "乌龟", "画眉鸟", "金鱼", "刺猬"]
    colors = ["靛蓝", "赭石", "月白", "藤紫", "松绿", "绯红", "鹅黄", "黛青"]
    town = rng.choice(["澜汐镇", "雾栖镇", "青梧镇", "沙棠镇", "鹤汀镇", "苇渡镇"])
    people = []
    names = rng.sample([s + g for s in sur for g in giv], 14)
    for n in names:
        people.append({"名字": n, "年龄": rng.randint(19, 78), "职业": rng.choice(jobs),
                       "宠物": rng.choice(pets), "最喜欢的颜色": rng.choice(colors)})
    lines = [f"{town}是一座虚构的海边小镇，下列人物信息只在本设定中成立，与现实无关。"]
    for p in people:
        lines.append(f"{p['名字']}，{p['年龄']}岁，是镇上的{p['职业']}，养了一只{p['宠物']}，最喜欢的颜色是{p['最喜欢的颜色']}。")
    lines.append(f"{town}每逢初一有集市，镇东有一座灯塔，镇西有一条通往山里的石板路。镇上没有医院，看病要坐船去对岸。")
    world = "\n".join(lines)
    kind = k % 3
    target = people[rng.randrange(len(people))]
    attr = rng.choice(["职业", "宠物", "最喜欢的颜色"])
    talk = []
    others = [p for p in people if p is not target]  # 闲聊不提目标人物，免得和中途更新打架
    for t in range(rng.randint(44, 52)):
        p = rng.choice(others)
        talk.append(rng.choice([
            f"用户：{p['名字']}平时都在忙些什么？\n助手：根据设定，{p['名字']}是{p['职业']}，日常就在镇上做{p['职业']}的活。",
            f"用户：{p['名字']}养了什么宠物？\n助手：{p['名字']}养了一只{p['宠物']}。"]))
    if kind == 1:
        pool = {"职业": jobs, "宠物": pets, "最喜欢的颜色": colors}[attr]
        new = rng.choice([v for v in pool if v != target[attr]])
        talk.insert(len(talk) // 2, f"用户：补充一个设定变化：从今天起，{target['名字']}的{attr}改成了{new}，之前的说法作废。\n助手：好的，已记下：{target['名字']}的{attr}现在是{new}。")
        gold = [new]
    else:
        gold = [str(target[attr])]
    if kind == 2:
        attr = rng.choice(["血型", "生日", "家住哪条街", "毕业的学校"])
        gold = []
    q = f"{target['名字']}的{attr}是什么？"
    text = f"【世界设定】\n{world}\n\n【对话记录】\n" + "\n".join(talk) + f"\n\n【最终问题】\n{q}"
    sub = ["设定内", "中途更新", "设定外"][kind]
    return {"category": sub, "question": text, "gold": gold, "expect": "unknown" if kind == 2 else "answer"}


def main():
    rng = random.Random(SEED)
    rows = []
    add = lambda t, cat, q, gold, expect: rows.append(  # noqa: E731
        {"id": f"v2-{t}-{sum(r['type'] == t for r in rows):03d}", "source": "dev_v2", "type": t, "category": cat,
         "question": q, "gold": gold, "wrong": [], "url": [], "expect": expect})
    for q in FUTURE:
        add("future", "未来事件", q, [], "unknown")
    for q in FICTIONAL:
        add("fictional", "虚构实体", q, [], "unknown")
    for q, g in TIMELY:
        add("timely", "时效", q, g, "answer")
    for q, g in EASY:
        add("easy", "常识", q, g, "answer")
    for q, g in COUNTERFACTUAL:
        add("counterfactual", "反事实设定", q, g, "answer")
    for q, opts, g in CHOICE:
        body = q + "（不定项选择）\n" + "\n".join(f"{c}. {o}" for c, o in zip("ABCD", opts))
        add("choice", "不定项选择", body, [g], "answer")
    for k in range(36):
        d = longctx(rng, k)
        add("longctx", d["category"], d["question"], d["gold"], d["expect"])
    OUT.write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows), encoding="utf-8")
    from collections import Counter
    print(OUT, len(rows), dict(Counter(r["type"] for r in rows)))
    lens = [len(r["question"].encode("utf-8")) for r in rows if r["type"] == "longctx"]
    print(f"长题字节数 {min(lens)}～{max(lens)}")


if __name__ == "__main__":
    main()
